import assert from 'node:assert/strict';
// @ts-ignore Node runner requires source extension.
import {materialCost,unitPriceFromTotal,applyMutation,seasonStats,stockBalance,type Stock,type OrchardRecord,type Mutation,type Farm} from '../lib/orchard.ts';
const stock:Stock={id:crypto.randomUUID(),kind:'stock',name:'Nawóz testowy',category:'fertilizer',unit:'l',initialAmount:5,minimum:0,pricePerUnit:unitPriceFromTotal(5,150),date:'2026-03-01',version:1,note:''};
const materials=[{stockId:stock.id,amount:2,unit:'l' as const}];
const treatment:OrchardRecord={id:crypto.randomUUID(),kind:'treatment',treatment:'Oprysk',plotId:null,product:'',amount:100,unit:'l',cost:999,costSource:'inventory',materials,date:'2026-04-01',version:0,note:''};
const add=(record:OrchardRecord):Mutation=>({action:'upsert',requestId:crypto.randomUUID(),expectedVersion:record.version,record});
const farm:Farm={records:[stock],appliedIds:[]};
assert.equal(materialCost(materials,[stock],treatment.date).cost,60);
const operation=add(treatment),saved=applyMutation(farm,operation);
const savedTreatment=saved.records.find(r=>r.id===treatment.id)!;
assert.equal(savedTreatment.kind==='treatment'&&savedTreatment.cost,60,'Server derives cost rather than trusting supplied cost.');
assert.equal(stockBalance(stock,saved.records),3);
assert.equal(seasonStats(saved.records,'2026').costs,60,'Purchase is not counted a second time in profit.');
assert.deepEqual(applyMutation(saved,operation),saved);
const purchase:OrchardRecord={id:crypto.randomUUID(),kind:'purchase',stockId:stock.id,amount:5,unit:'l',pricePerUnit:50,date:'2026-03-10',version:0,note:''};
assert.equal(materialCost(materials,[stock,purchase],treatment.date).cost,80);
assert.equal(materialCost(materials,[stock,{...purchase,date:'2026-05-01'}],treatment.date).cost,60);
const withPurchase=applyMutation(saved,add(purchase));
assert.equal(seasonStats(withPurchase.records,'2026').costs,60,'New purchases do not rewrite saved treatment cost.');
const edited=applyMutation(saved,add({...treatment,version:1,materials:[{...materials[0],amount:1}]}));
assert.equal(seasonStats(edited.records,'2026').costs,30);
assert.equal(stockBalance(stock,edited.records),4);
const removed=applyMutation(edited,{action:'delete',id:treatment.id,expectedVersion:2,requestId:crypto.randomUUID()});
assert.equal(seasonStats(removed.records,'2026').costs,0);assert.equal(stockBalance(stock,removed.records),5);
assert.equal(materialCost(materials,[{...stock,pricePerUnit:0}],treatment.date).cost,0);
assert.equal(materialCost(materials,[{...stock,pricePerUnit:null}],treatment.date).cost,null);
assert.equal(materialCost(materials,[stock,{...purchase,pricePerUnit:null}],treatment.date).cost,null);
assert.throws(()=>applyMutation({records:[{...stock,pricePerUnit:null}],appliedIds:[]},operation),/cenę zakupu/);
assert.throws(()=>applyMutation(farm,add({...treatment,materials:[]})),/Wybierz z magazynu/);
assert.throws(()=>applyMutation(farm,add({...treatment,materials:[{...materials[0],amount:6}]})),/Za mało/);
const powder:Stock={...stock,id:crypto.randomUUID(),name:'Nawóz sypki',unit:'kg',pricePerUnit:10};
assert.equal(materialCost([...materials,{stockId:powder.id,amount:0.25,unit:'kg'}],[stock,powder],treatment.date).cost,62.5);
const legacy=applyMutation(farm,add({...treatment,costSource:undefined,materials:[],cost:123}));
assert.equal(seasonStats(legacy.records,'2026').costs,123,'Legacy manually entered costs remain intact.');
console.log('PASS: automatic fertilizer costs, weighted dated prices, missing/zero prices, mixture, snapshots, stats, edits, deletion and retries.');
