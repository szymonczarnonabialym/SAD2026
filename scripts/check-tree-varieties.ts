import assert from 'node:assert/strict';
// @ts-ignore Node TypeScript runner needs the extension.
import {applyMutation,recordSchema,plotTreeCounts,treesFor,treesForVariety,availableVarieties,varietySeasonStats,seasonStats,unitPriceFromTotal,stockCosts,type Plot,type OrchardRecord,type Farm,type Stock} from '../lib/orchard.ts';
const base={date:'2026-03-01',note:'LOCAL TEST',version:0};
const add=(record:OrchardRecord)=>({action:'upsert' as const,requestId:crypto.randomUUID(),expectedVersion:record.version,record:recordSchema.parse(record)});
const plot:Plot={...base,id:crypto.randomUUID(),kind:'plot',name:'Jeden sad',variety:'Wanda',varieties:['Wanda','Vega','Regina'],initialTrees:150,area:1,plantedYear:2020,rootstock:''};
// Counts can be supplied on the first save, with all harvests sharing one plot.
const firstSave:Plot={...plot,varietyTrees:[{variety:'Wanda',trees:10},{variety:'Vega',trees:20},{variety:'Regina',trees:120}]};
let created=applyMutation({records:[],appliedIds:[]},add(firstSave));
for(const [variety,boxes10] of [['Wanda',5],['Regina',10]] as const){
 created=applyMutation(created,add({...base,id:crypto.randomUUID(),kind:'harvest',plotId:plot.id,variety,boxes5:0,boxes10,pricePerKg:8}));
}
assert.equal(created.records.filter(r=>r.kind==='plot').length,1);
assert.equal(plotTreeCounts(firstSave,created.records).unassigned,0);
assert.equal(varietySeasonStats(created.records,'2026','Wanda',plot.id).kg,50);
assert.equal(varietySeasonStats(created.records,'2026','Regina',plot.id).kg,100);
assert.equal(seasonStats(created.records,'2026',plot.id).sweet.kg,150);
assert.equal(seasonStats(created.records,'2026',plot.id).sales,1200);
let farm:Farm=applyMutation({records:[],appliedIds:[]},add(plot));
assert.equal(farm.records.filter(r=>r.kind==='plot').length,1);
assert.equal(plotTreeCounts(plot,[]).unassigned,150);
assert.equal(treesForVariety([plot],[],'Wanda'),null);
const allocated:Plot={...plot,version:1,varietyTrees:[{variety:'Wanda',trees:10},{variety:'Vega',trees:20},{variety:'Regina',trees:30}]};
farm=applyMutation(farm,add(allocated));
assert.equal(plotTreeCounts(allocated,farm.records).unassigned,90);
assert.equal(treesForVariety([allocated],farm.records,'Regina'),30);
assert.throws(()=>applyMutation(farm,add({...allocated,version:2,varietyTrees:[{variety:'Wanda',trees:151}]})),/Suma drzew/);
assert.throws(()=>applyMutation(farm,add({...allocated,version:2,varietyTrees:[{variety:'Wanda',trees:1},{variety:'Wanda',trees:2}]})),/tylko raz/);
assert.throws(()=>applyMutation(farm,add({...allocated,version:2,varietyTrees:[{variety:'Burlat',trees:1}]})),/wybranej odmiany/);
const custom:Plot={...allocated,version:2,varieties:[...allocated.varieties!,'Sylvia'],varietyTrees:[...allocated.varietyTrees!,{variety:'Sylvia',trees:90}]};
farm=applyMutation(farm,add(custom));
assert.equal(plotTreeCounts(custom,farm.records).unassigned,0);
assert.ok(availableVarieties(farm.records).includes('Sylvia'));
const change:OrchardRecord={...base,id:crypto.randomUUID(),kind:'trees',plotId:plot.id,variety:'Wanda',treeChange:-3};
farm=applyMutation(farm,add(change));
assert.equal(treesFor(custom,farm.records),147);assert.equal(treesForVariety([custom],farm.records,'Wanda'),7);
assert.throws(()=>applyMutation(farm,add({...change,id:crypto.randomUUID(),treeChange:-8})),/wybranej odmiany/);
assert.throws(()=>applyMutation(farm,add({...change,id:crypto.randomUUID(),variety:null,treeChange:-1})),/Bez|bez przypisanej/);
farm=applyMutation(farm,add({...change,id:crypto.randomUUID(),treeChange:2}));
assert.equal(treesForVariety([custom],farm.records,'Wanda'),9);
const harvest:OrchardRecord={...base,id:crypto.randomUUID(),kind:'harvest',plotId:plot.id,variety:'Sylvia',boxes5:2,boxes10:3,pricePerKg:8};
farm=applyMutation(farm,add(harvest));
farm=applyMutation(farm,add({...harvest,id:crypto.randomUUID(),date:'2027-07-01',boxes5:4,boxes10:6,pricePerKg:10}));
assert.deepEqual(varietySeasonStats(farm.records,'2026','Sylvia',plot.id),{kg:40,sales:320,missingPrices:0});
assert.deepEqual(varietySeasonStats(farm.records,'2027','Sylvia',plot.id),{kg:80,sales:800,missingPrices:0});
assert.equal(seasonStats(farm.records,'2027',plot.id).sweet.kg,80);
assert.equal(seasonStats(farm.records,'2027',plot.id).result,800);
assert.throws(()=>applyMutation(farm,add({...custom,version:3,varieties:allocated.varieties,varietyTrees:allocated.varietyTrees})),/Odmiana/);
assert.equal(recordSchema.safeParse({...custom,varietyTrees:[{variety:'Wanda',trees:-1}]}).success,false);
assert.equal(recordSchema.safeParse({...custom,varietyTrees:[{variety:'Wanda',trees:0.5}]}).success,false);
const legacy:Plot={...plot,varieties:undefined,variety:'Regina'};
assert.equal(treesForVariety([legacy],[],'Regina'),150);
assert.equal(unitPriceFromTotal(5,150),30);assert.equal(unitPriceFromTotal(3,100),100/3);
assert.equal(unitPriceFromTotal(5,0),0);assert.equal(unitPriceFromTotal(0,null),null);
assert.throws(()=>unitPriceFromTotal(0,150),/dodatnią ilość/);
const stock:Stock={...base,id:crypto.randomUUID(),kind:'stock',name:'Opakowanie 5 l',unit:'l',category:'protection',initialAmount:5,minimum:0,pricePerUnit:unitPriceFromTotal(5,150)};
const purchase:OrchardRecord={...base,id:crypto.randomUUID(),kind:'purchase',stockId:stock.id,amount:3,unit:'l',pricePerUnit:unitPriceFromTotal(3,120)};
assert.equal(stockCosts(stock,[stock,purchase]).paid,270);assert.equal(stockCosts(stock,[stock,purchase]).average,33.75);
console.log('PASS: one 150-tree plot, partial/full allocation, custom varieties, variety removals/additions, membership/history safeguards, yearly kilograms/sales, legacy records and total purchase pricing.');
